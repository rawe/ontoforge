#!/usr/bin/env node
// One-command development identity provider: starts Keycloak, waits for it, reconciles the
// realm, clients, scopes, registration policies, administrators and test users, writes the
// OntoForge configuration and verifies it. Reruns change only what differs: no realm is
// deleted, no duplicate is created, no password is reset. See USAGE.md beside this file.
//
//   node scripts/keycloak/setup.mjs          (./dev.sh keycloak)
//   node scripts/keycloak/setup.mjs reset    remove the container and its volume

import { execFileSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const COMPOSE = path.join(ROOT, 'docker/keycloak/compose.yml');
const SECRETS = path.join(ROOT, 'env/keycloak.local.env');

export const KEYCLOAK_URL = 'http://localhost:8180';
export const REALM = 'ontoforge';
export const ISSUER = `${KEYCLOAK_URL}/realms/${REALM}`;
const AUDIENCE = 'ontoforge-api';
const PERMANENT_ADMIN = 'ontoforge-admin';
const BOOTSTRAP_ADMIN = 'bootstrap-admin';
const READY_SECONDS = 180;

/** Browser origins of the two stacks: Vite (solo) and the harness's frontend container. */
const ORIGINS = ['http://localhost:5173', 'http://localhost:13000'];

/** The application realm's test identities: username → profile. */
export const USERS = {
  admin: { firstName: 'Ada', lastName: 'Admin' },
  reader: { firstName: 'Rita', lastName: 'Reader' },
  writer: { firstName: 'Wim', lastName: 'Writer' },
  newcomer: { firstName: 'Nina', lastName: 'Newcomer' },
};

/** Generated once, kept in env/keycloak.local.env, never printed. */
const SECRET_NAMES = [
  'KC_BOOTSTRAP_ADMIN_PASSWORD',
  'KEYCLOAK_ADMIN_PASSWORD',
  'OIDC_CLIENT_SECRET',
  'SERVICE_CLIENT_SECRET',
  ...Object.keys(USERS).map((u) => `USER_${u.toUpperCase()}_PASSWORD`),
];

function fail(message) {
  console.error(`\nKeycloak setup failed: ${message}`);
  process.exit(1);
}

function step(message) {
  console.log(`- ${message}`);
}

// --- Secrets --------------------------------------------------------------------------

export function readEnvFile(file) {
  const values = {};
  if (!existsSync(file)) return values;
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (match) values[match[1]] = match[2];
  }
  return values;
}

function ensureSecrets() {
  const values = readEnvFile(SECRETS);
  let added = 0;
  values.KC_BOOTSTRAP_ADMIN_USERNAME ??= BOOTSTRAP_ADMIN;
  values.KEYCLOAK_ADMIN_USERNAME ??= PERMANENT_ADMIN;
  for (const name of SECRET_NAMES) {
    if (!values[name]) {
      values[name] = randomBytes(18).toString('base64url');
      added += 1;
    }
  }
  const lines = [
    '# Generated by scripts/keycloak/setup.mjs — development secrets, never commit.',
    '# Deleting this file and running `./dev.sh keycloak reset` starts over.',
    ...Object.entries(values).map(([k, v]) => `${k}=${v}`),
    '',
  ];
  writeFileSync(SECRETS, lines.join('\n'), { mode: 0o600 });
  chmodSync(SECRETS, 0o600);
  step(added ? `secrets: ${added} generated into ${path.relative(ROOT, SECRETS)}` : `secrets: kept ${path.relative(ROOT, SECRETS)}`);
  return values;
}

// --- Container ------------------------------------------------------------------------

function compose(...args) {
  execFileSync('docker', ['compose', '--env-file', SECRETS, '-f', COMPOSE, ...args], { stdio: 'inherit' });
}

async function waitReady() {
  const deadline = Date.now() + READY_SECONDS * 1000;
  let last = 'no answer';
  while (Date.now() < deadline) {
    try {
      const res = await fetch(`${KEYCLOAK_URL}/realms/master/.well-known/openid-configuration`);
      if (res.ok) return;
      last = `HTTP ${res.status}`;
    } catch (error) {
      last = error.cause?.code ?? error.message;
    }
    await new Promise((r) => setTimeout(r, 2000));
  }
  fail(
    `Keycloak did not answer at ${KEYCLOAK_URL} within ${READY_SECONDS} s (${last}). ` +
      `Check 'docker compose -f docker/keycloak/compose.yml logs keycloak'; ` +
      `port 8180 must be free and Docker needs about 1 GB.`,
  );
}

// --- Admin REST -----------------------------------------------------------------------

async function adminToken(username, password) {
  const res = await fetch(`${KEYCLOAK_URL}/realms/master/protocol/openid-connect/token`, {
    method: 'POST',
    headers: { 'content-type': 'application/x-www-form-urlencoded' },
    body: new URLSearchParams({ grant_type: 'password', client_id: 'admin-cli', username, password }),
  });
  if (!res.ok) return null;
  return (await res.json()).access_token;
}

let token = null;

async function api(method, pathname, body, { allowConflict = false } = {}) {
  const res = await fetch(`${KEYCLOAK_URL}/admin/realms${pathname}`, {
    method,
    headers: {
      authorization: `Bearer ${token}`,
      ...(body !== undefined ? { 'content-type': 'application/json' } : {}),
    },
    body: body !== undefined ? JSON.stringify(body) : undefined,
  });
  if (res.status === 404 && method === 'GET') return null;
  // Attaching what is already attached answers 409: already the wanted state.
  if (res.status === 409 && allowConflict) return null;
  if (!res.ok) {
    const text = await res.text();
    fail(`${method} /admin/realms${pathname} answered ${res.status}: ${text.slice(0, 300)}`);
  }
  const text = await res.text();
  return text ? JSON.parse(text) : null;
}

async function findUser(realm, username) {
  const found = await api('GET', `/${realm}/users?username=${encodeURIComponent(username)}&exact=true`);
  return found?.[0] ?? null;
}

/** Permanent master administrator; the temporary bootstrap one is deleted once it exists. */
async function ensureAdministrator(secrets) {
  token = await adminToken(secrets.KEYCLOAK_ADMIN_USERNAME, secrets.KEYCLOAK_ADMIN_PASSWORD);
  if (token) {
    step(`Keycloak administrator '${secrets.KEYCLOAK_ADMIN_USERNAME}': signed in`);
  } else {
    token = await adminToken(secrets.KC_BOOTSTRAP_ADMIN_USERNAME, secrets.KC_BOOTSTRAP_ADMIN_PASSWORD);
    if (!token) {
      fail(
        'neither the permanent nor the bootstrap Keycloak administrator can sign in. ' +
          'The volume holds administrators from other secrets: run `./dev.sh keycloak reset`, then `./dev.sh keycloak`.',
      );
    }
    let admin = await findUser('master', secrets.KEYCLOAK_ADMIN_USERNAME);
    if (!admin) {
      await api('POST', '/master/users', {
        username: secrets.KEYCLOAK_ADMIN_USERNAME,
        enabled: true,
        email: 'keycloak-admin@ontoforge.test',
        emailVerified: true,
        firstName: 'Keycloak',
        lastName: 'Administrator',
        credentials: [{ type: 'password', value: secrets.KEYCLOAK_ADMIN_PASSWORD, temporary: false }],
      });
      admin = await findUser('master', secrets.KEYCLOAK_ADMIN_USERNAME);
    }
    const role = await api('GET', '/master/roles/admin');
    await api('POST', `/master/users/${admin.id}/role-mappings/realm`, [role], { allowConflict: true });
    token = await adminToken(secrets.KEYCLOAK_ADMIN_USERNAME, secrets.KEYCLOAK_ADMIN_PASSWORD);
    if (!token) fail(`the new administrator '${secrets.KEYCLOAK_ADMIN_USERNAME}' cannot sign in`);
    step(`Keycloak administrator '${secrets.KEYCLOAK_ADMIN_USERNAME}': created with the realm role admin`);
  }
  const bootstrap = await findUser('master', secrets.KC_BOOTSTRAP_ADMIN_USERNAME);
  if (bootstrap) {
    await api('DELETE', `/master/users/${bootstrap.id}`);
    step(`temporary bootstrap administrator '${secrets.KC_BOOTSTRAP_ADMIN_USERNAME}': deleted`);
  }
}

// --- Realm ----------------------------------------------------------------------------

const REALM_SETTINGS = {
  realm: REALM,
  enabled: true,
  displayName: 'OntoForge (development)',
  registrationAllowed: false,
  resetPasswordAllowed: false,
  loginWithEmailAllowed: true,
  duplicateEmailsAllowed: false,
  bruteForceProtected: true,
  // Short access tokens: a revoked Keycloak session stops minting new ones soon.
  accessTokenLifespan: 300,
};

async function ensureRealm() {
  const existing = await api('GET', `/${REALM}`);
  if (!existing) {
    await api('POST', '', REALM_SETTINGS);
    step(`realm '${REALM}': created`);
  } else {
    await api('PUT', `/${REALM}`, { ...REALM_SETTINGS });
    step(`realm '${REALM}': settings reconciled`);
  }
}

/** The audience every OntoForge access token carries. A realm optional scope: every client
 * — dynamically registered MCP clients included — may ask for it, and only a client that asks
 * gets a token OntoForge accepts. */
async function ensureAudienceScope() {
  const scopes = await api('GET', `/${REALM}/client-scopes`);
  let scope = scopes.find((s) => s.name === AUDIENCE);
  const mapper = {
    name: 'audience',
    protocol: 'openid-connect',
    protocolMapper: 'oidc-audience-mapper',
    config: {
      'included.custom.audience': AUDIENCE,
      'access.token.claim': 'true',
      'id.token.claim': 'false',
      'introspection.token.claim': 'true',
    },
  };
  if (!scope) {
    await api('POST', `/${REALM}/client-scopes`, {
      name: AUDIENCE,
      description: 'OntoForge API audience',
      protocol: 'openid-connect',
      attributes: { 'include.in.token.scope': 'false', 'display.on.consent.screen': 'false' },
      protocolMappers: [mapper],
    });
    scope = (await api('GET', `/${REALM}/client-scopes`)).find((s) => s.name === AUDIENCE);
    step(`client scope '${AUDIENCE}': created`);
  } else {
    const mappers = await api('GET', `/${REALM}/client-scopes/${scope.id}/protocol-mappers/models`);
    const current = mappers.find((m) => m.name === 'audience');
    if (!current) {
      await api('POST', `/${REALM}/client-scopes/${scope.id}/protocol-mappers/models`, mapper);
    } else {
      await api('PUT', `/${REALM}/client-scopes/${scope.id}/protocol-mappers/models/${current.id}`, { ...current, config: mapper.config });
    }
    step(`client scope '${AUDIENCE}': reconciled`);
  }
  const defaults = await api('GET', `/${REALM}/default-default-client-scopes`);
  if (defaults.some((s) => s.id === scope.id)) {
    await api('DELETE', `/${REALM}/default-default-client-scopes/${scope.id}`);
  }
  await api('PUT', `/${REALM}/default-optional-client-scopes/${scope.id}`, undefined, { allowConflict: true });
  return scope;
}

function clientDefinitions(secrets) {
  return [
    {
      clientId: AUDIENCE,
      name: 'OntoForge API (audience only)',
      publicClient: false,
      bearerOnly: true,
      standardFlowEnabled: false,
      directAccessGrantsEnabled: false,
      serviceAccountsEnabled: false,
    },
    {
      clientId: 'ontoforge-web',
      name: 'OntoForge web client (the server signs browsers in)',
      publicClient: false,
      secret: secrets.OIDC_CLIENT_SECRET,
      standardFlowEnabled: true,
      implicitFlowEnabled: false,
      directAccessGrantsEnabled: false,
      serviceAccountsEnabled: false,
      redirectUris: ORIGINS.map((o) => `${o}/api/auth/callback`),
      webOrigins: [],
      attributes: {
        'pkce.code.challenge.method': 'S256',
        'post.logout.redirect.uris': ORIGINS.map((o) => `${o}/*`).join('##'),
      },
    },
    {
      clientId: 'ontoforge-mcp',
      name: 'OntoForge MCP and command-line clients',
      publicClient: true,
      standardFlowEnabled: true,
      implicitFlowEnabled: false,
      directAccessGrantsEnabled: false,
      serviceAccountsEnabled: false,
      redirectUris: ['http://127.0.0.1/*', 'http://localhost/*'],
      webOrigins: [],
      attributes: { 'pkce.code.challenge.method': 'S256' },
      audience: 'optional',
    },
    {
      clientId: 'ontoforge-service',
      name: 'OntoForge service principal (client credentials)',
      publicClient: false,
      secret: secrets.SERVICE_CLIENT_SECRET,
      standardFlowEnabled: false,
      implicitFlowEnabled: false,
      directAccessGrantsEnabled: false,
      serviceAccountsEnabled: true,
      audience: 'default',
    },
  ];
}

async function ensureClients(secrets, audienceScope) {
  for (const { audience, ...definition } of clientDefinitions(secrets)) {
    const found = (await api('GET', `/${REALM}/clients?clientId=${encodeURIComponent(definition.clientId)}`))?.[0];
    let id;
    if (!found) {
      await api('POST', `/${REALM}/clients`, { protocol: 'openid-connect', enabled: true, ...definition });
      id = (await api('GET', `/${REALM}/clients?clientId=${encodeURIComponent(definition.clientId)}`))[0].id;
      step(`client '${definition.clientId}': created`);
    } else {
      id = found.id;
      await api('PUT', `/${REALM}/clients/${id}`, {
        ...found,
        ...definition,
        attributes: { ...found.attributes, ...definition.attributes },
      });
      step(`client '${definition.clientId}': reconciled`);
    }
    // The service principal always gets the audience; the MCP client asks for it.
    if (audience) {
      const other = audience === 'default' ? 'optional' : 'default';
      const attached = await api('GET', `/${REALM}/clients/${id}/${other}-client-scopes`);
      if (attached.some((s) => s.id === audienceScope.id)) {
        await api('DELETE', `/${REALM}/clients/${id}/${other}-client-scopes/${audienceScope.id}`);
      }
      await api('PUT', `/${REALM}/clients/${id}/${audience}-client-scopes/${audienceScope.id}`, undefined, { allowConflict: true });
    }
  }
}

/** Anonymous dynamic client registration, as MCP clients use it: only loopback redirect
 * URIs, and the audience scope among the scopes such a client may receive. */
async function ensureRegistrationPolicies() {
  const type = 'org.keycloak.services.clientregistration.policy.ClientRegistrationPolicy';
  const components = await api('GET', `/${REALM}/components?type=${encodeURIComponent(type)}`);
  const anonymous = components.filter((c) => c.subType === 'anonymous');
  const trusted = anonymous.find((c) => c.providerId === 'trusted-hosts');
  if (!trusted) fail('the realm has no anonymous trusted-hosts registration policy');
  await api('PUT', `/${REALM}/components/${trusted.id}`, {
    ...trusted,
    config: {
      ...trusted.config,
      'trusted-hosts': ['localhost', '127.0.0.1'],
      // Docker's port mapping hides the caller's address; the redirect URIs still must be loopback.
      'host-sending-registration-request-must-match': ['false'],
      'client-uris-must-match': ['true'],
    },
  });
  const allowed = anonymous.find((c) => c.providerId === 'allowed-client-templates');
  if (allowed) {
    const scopes = new Set(allowed.config?.['allowed-client-scopes'] ?? []);
    scopes.add(AUDIENCE);
    await api('PUT', `/${REALM}/components/${allowed.id}`, {
      ...allowed,
      config: { ...allowed.config, 'allowed-client-scopes': [...scopes], 'allow-default-scopes': ['true'] },
    });
  }
  step('dynamic client registration: loopback redirect URIs only, audience scope allowed');
}

async function ensureUsers(secrets) {
  const ids = {};
  for (const [username, profile] of Object.entries(USERS)) {
    let user = await findUser(REALM, username);
    if (!user) {
      await api('POST', `/${REALM}/users`, {
        username,
        enabled: true,
        email: `${username}@ontoforge.test`,
        emailVerified: true,
        ...profile,
        credentials: [
          { type: 'password', value: secrets[`USER_${username.toUpperCase()}_PASSWORD`], temporary: false },
        ],
      });
      user = await findUser(REALM, username);
      step(`user '${username}': created`);
    } else {
      // Profile only; the password and the enabled flag stay as they are.
      await api('PUT', `/${REALM}/users/${user.id}`, {
        ...user,
        email: `${username}@ontoforge.test`,
        emailVerified: true,
        ...profile,
      });
      step(`user '${username}': present (password untouched)`);
    }
    ids[username] = user.id;
  }
  return ids;
}

async function serviceSubject() {
  const client = (await api('GET', `/${REALM}/clients?clientId=ontoforge-service`))[0];
  return (await api('GET', `/${REALM}/clients/${client.id}/service-account-user`)).id;
}

// --- OntoForge configuration ----------------------------------------------------------

/** A committed preset plus the generated values: the one env file a server reads. */
function writeServerConfig(preset, target, values) {
  const base = readFileSync(path.join(ROOT, preset), 'utf8');
  const lines = [
    base.trimEnd(),
    '',
    '# --- Generated by scripts/keycloak/setup.mjs (never commit) ----------------------',
    ...Object.entries(values).map(([k, v]) => `${k}=${v}`),
    '',
  ];
  writeFileSync(path.join(ROOT, target), lines.join('\n'), { mode: 0o600 });
  step(`server configuration: ${target} (from ${preset})`);
}

// --- Verification ---------------------------------------------------------------------

function claims(jwt) {
  return JSON.parse(Buffer.from(jwt.split('.')[1], 'base64url').toString('utf8'));
}

async function verify(secrets, subjects) {
  const discovery = await fetch(`${ISSUER}/.well-known/openid-configuration`);
  if (!discovery.ok) fail(`discovery answered ${discovery.status}`);
  const metadata = await discovery.json();
  if (metadata.issuer !== ISSUER) fail(`issuer is '${metadata.issuer}', expected '${ISSUER}'`);
  const res = await fetch(metadata.token_endpoint, {
    method: 'POST',
    headers: { 'content-type': 'application/x-www-form-urlencoded' },
    body: new URLSearchParams({
      grant_type: 'client_credentials',
      client_id: 'ontoforge-service',
      client_secret: secrets.SERVICE_CLIENT_SECRET,
    }),
  });
  if (!res.ok) fail(`client credentials token answered ${res.status}`);
  const access = claims((await res.json()).access_token);
  const audience = [access.aud].flat();
  if (!audience.includes(AUDIENCE)) fail(`the service token's audience is ${JSON.stringify(access.aud)}, not '${AUDIENCE}'`);
  if (access.iss !== ISSUER) fail(`the service token's issuer is '${access.iss}'`);
  if (access.sub !== subjects.service) fail('the service token names another subject');
  // Exactly one of everything the script owns: a rerun must never duplicate.
  const clients = await api('GET', `/${REALM}/clients?max=1000`);
  for (const { clientId } of clientDefinitions(secrets)) {
    const count = clients.filter((c) => c.clientId === clientId).length;
    if (count !== 1) fail(`client '${clientId}' exists ${count} times`);
  }
  const scopes = (await api('GET', `/${REALM}/client-scopes`)).filter((s) => s.name === AUDIENCE).length;
  if (scopes !== 1) fail(`client scope '${AUDIENCE}' exists ${scopes} times`);
  for (const username of Object.keys(USERS)) {
    const count = (await api('GET', `/${REALM}/users?username=${username}&exact=true`)).length;
    if (count !== 1) fail(`user '${username}' exists ${count} times`);
  }
  const masterAdmins = await api('GET', `/master/users?max=100`);
  if (masterAdmins.some((u) => u.username === secrets.KC_BOOTSTRAP_ADMIN_USERNAME)) {
    fail('the temporary bootstrap administrator still exists');
  }
  if (!(await adminToken(secrets.KEYCLOAK_ADMIN_USERNAME, secrets.KEYCLOAK_ADMIN_PASSWORD))) {
    fail('the permanent Keycloak administrator cannot sign in');
  }
  step(
    `verified: issuer ${ISSUER}, audience '${AUDIENCE}' in a client-credentials token, ` +
      `one of each client/scope/user, no bootstrap administrator, administrator sign-in`,
  );
}

// --- Main -----------------------------------------------------------------------------

async function main() {
  if (process.argv[2] === 'reset') {
    if (!existsSync(SECRETS)) ensureSecrets();
    compose('down', '--volumes', '--remove-orphans');
    console.log('Keycloak container and volume removed; env/keycloak.local.env kept.');
    return;
  }
  if (process.argv[2] === 'down') {
    if (!existsSync(SECRETS)) ensureSecrets();
    compose('down', '--remove-orphans');
    return;
  }
  console.log('Keycloak development setup');
  const secrets = ensureSecrets();
  compose('up', '-d');
  await waitReady();
  step(`Keycloak answers at ${KEYCLOAK_URL}`);
  await ensureAdministrator(secrets);
  await ensureRealm();
  const audienceScope = await ensureAudienceScope();
  await ensureClients(secrets, audienceScope);
  await ensureRegistrationPolicies();
  const users = await ensureUsers(secrets);
  const subjects = { ...users, service: await serviceSubject() };
  const generated = {
    OIDC_CLIENT_SECRET: secrets.OIDC_CLIENT_SECRET,
    AUTH_ADMIN_SUBJECT: users.admin,
  };
  writeServerConfig('env/auth.env', 'env/auth.local.env', generated);
  writeServerConfig('env/scale-auth.env', 'env/scale-auth.local.env', generated);
  // The subjects, for scripted checks that admit the service principal.
  const subjectLines = Object.entries(subjects).map(([k, v]) => `SUBJECT_${k.toUpperCase()}=${v}`);
  writeFileSync(path.join(ROOT, 'env/keycloak-subjects.local.env'), `${subjectLines.join('\n')}\n`, { mode: 0o600 });
  await verify(secrets, subjects);
  console.log(`
Ready.
  Issuer            ${ISSUER}
  Keycloak console  ${KEYCLOAK_URL}/admin  (user '${secrets.KEYCLOAK_ADMIN_USERNAME}')
  Test users        ${Object.keys(USERS).join(', ')}  (realm '${REALM}')
  Passwords         env/keycloak.local.env
  Solo stack        ./dev.sh env/auth.local.env
  Scale stack       ./dev.sh scale up env/scale-auth.local.env`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
